/**
 * Chat-context build integrity (CHAT-03 / AI-SPEC §5.6 / D-06..D-11 / D-04)
 *
 * Asserts invariants on the generated src/data/portfolio-context.json:
 *   - All 7 active project slugs present (D-04 exclusion LIFTED — #7 is public)
 *   - Projects/7 (Multi-Chain EVM) NOW present and fully untruncated (D-04)
 *   - Per-project caseStudy + extendedReference fields present and non-empty (D-01/D-02)
 *   - Token-count floor >= 4096 (AI-SPEC §3 pitfall #1 — Haiku 4.5 cache minimum)
 *   - Static split keys + generated keys BOTH present (D-08)
 *   - education wired to src/data/education.ts SSoT (D-07)
 *   - experience is a reverse-chron structured array (D-01/D-03/D-09)
 *   - additive D-08 skills machine-verified in the corpus (D-08)
 *
 * Target artifact is generated by scripts/build-chat-context.mjs.
 * Phase 25 Wave-0 retarget: the 7-slug / education / experience-array / #7-
 * untruncated / skills-presence assertions are RED-by-design until 25-02 adds
 * the skills + positioning and 25-03 regenerates the corpus (7 projects +
 * structured experience array + education from education.ts). Mirrors 22-01.
 */
import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import portfolioContext from "../../src/data/portfolio-context.json";
import { EDUCATION, CREDENTIALS } from "../../src/data/education";
import {
  truncateReadme,
  buildProjectBlock,
} from "../../scripts/build-chat-context.mjs";
import { wordCount } from "../../scripts/sync-projects.mjs";

const EXPECTED_SLUGS = [
  "clipify",
  "multi-chain-evm",
  "nfl-predict",
  "optimize-ai",
  "seatwatch",
];

// Cheap char-based token estimator (matches generator's estimateTokens helper).
// Haiku 4.5 cache minimum is 4096 tokens; char / 4 is the SDK's conservative rule.
const MIN_TOKENS = 4096;

describe("Chat Context Integrity (CHAT-03 / §5.6)", () => {
  it("contains the 5 expected project slugs (D-04 exclusion lifted)", () => {
    const slugs = (portfolioContext.projects as Array<{ page: string }>)
      .map((p) => p.page.replace("/projects/", ""))
      .sort();
    expect(slugs).toEqual(EXPECTED_SLUGS);
  });

  it("projects[] has exactly 5 entries (Projects/7 now ingested)", () => {
    expect((portfolioContext.projects as unknown[]).length).toBe(5);
  });

  it("every project has a non-empty caseStudy field (D-01 MDX body)", () => {
    const failures: string[] = [];
    for (const project of portfolioContext.projects as Array<{
      page: string;
      caseStudy?: string;
    }>) {
      if (!project.caseStudy || project.caseStudy.trim().length < 100) {
        failures.push(`${project.page}: caseStudy missing or <100 chars`);
      }
    }
    expect(failures).toEqual([]);
  });

  it("every project has a non-empty extendedReference.content field (D-02 Projects/*.md below-fence)", () => {
    const failures: string[] = [];
    for (const project of portfolioContext.projects as Array<{
      page: string;
      extendedReference?: { content?: string; truncated?: boolean };
    }>) {
      if (
        !project.extendedReference ||
        !project.extendedReference.content ||
        project.extendedReference.content.trim().length < 100
      ) {
        failures.push(
          `${project.page}: extendedReference.content missing or <100 chars`
        );
      }
    }
    expect(failures).toEqual([]);
  });

  it("total serialized size >= 4096 tokens (Haiku 4.5 cache floor; AI-SPEC §3 pitfall #1)", () => {
    const serialized = JSON.stringify(portfolioContext);
    const estimatedTokens = Math.ceil(serialized.length / 4);
    expect(
      estimatedTokens,
      `estimated tokens ${estimatedTokens} below Haiku 4.5 floor ${MIN_TOKENS}; cache would silently disable`
    ).toBeGreaterThanOrEqual(MIN_TOKENS);
  });

  it("contains all D-08 static identity keys (personal, education, skills, contact, siteStack)", () => {
    expect(portfolioContext).toHaveProperty("personal");
    expect(portfolioContext).toHaveProperty("education");
    expect(portfolioContext).toHaveProperty("skills");
    expect(portfolioContext).toHaveProperty("contact");
    expect(portfolioContext).toHaveProperty("siteStack");
  });

  it("contains all D-08 generated keys (projects, experience, about)", () => {
    expect(portfolioContext).toHaveProperty("projects");
    expect(portfolioContext).toHaveProperty("experience");
    expect(portfolioContext).toHaveProperty("about");
    const about = (portfolioContext as Record<string, unknown>).about as
      | Record<string, unknown>
      | undefined;
    expect(about).toBeDefined();
    // Chat about block is INTRO/P1/P3 (25-02 cut the chat P2 "boring tool first"
    // paragraph to match the Phase 24 site /about; 25-03 regenerated the corpus
    // without it). Assert EXACTLY intro/p1/p3 — no p2.
    expect(Object.keys(about as Record<string, unknown>).sort()).toEqual([
      "intro",
      "p1",
      "p3",
    ]);
  });

  it("education is wired to src/data/education.ts SSoT, not hard-pinned literals (D-07)", () => {
    // Compare the GENERATED education object against the imported education.ts
    // exports (the SSoT relationship). A build script that hard-coded the same
    // values would still pass a literal test; comparing against the imports
    // proves chat education can never silently drift from education.ts.
    // RED until 25-03 rewrites parseEducation to read graduation/transferredFrom/
    // certifications from education.ts (current corpus ships the stale 3-field shape).
    const education = (portfolioContext as Record<string, unknown>)
      .education as Record<string, unknown> | undefined;
    expect(education).toBeDefined();
    expect(education?.school).toBe(EDUCATION.institution);
    expect(education?.degree).toBe(EDUCATION.degree);
    expect(education?.graduation).toBe(EDUCATION.date);
    expect(education?.transferredFrom).toBe(EDUCATION.transferredFrom);
    expect(education?.certifications).toEqual(CREDENTIALS.map((c) => c.name));
  });

  it("experience is a reverse-chron structured array, Holloway first with Balfour present (D-01/D-03/D-09)", () => {
    // RED until 25-03's experience-collection reader emits the structured array.
    const experience = (portfolioContext as Record<string, unknown>)
      .experience as
      | Array<{
          role: string;
          company: string;
          dateRange: string;
          summary: string;
        }>
      | undefined;
    expect(Array.isArray(experience)).toBe(true);
    expect(experience?.length).toBe(2);
    // reverse-chronological: Holloway (current) first (D-01/D-09)
    expect(experience?.[0].company).toBe("Holloway Company");
    // Balfour present somewhere in the array (D-03)
    expect(
      experience?.some((e) => e.company === "Balfour Beatty")
    ).toBe(true);
    for (const e of experience ?? []) {
      expect(typeof e.summary).toBe("string");
      const floor = e.company === "Holloway Company" ? 40 : 0;
      expect(e.summary.trim().length).toBeGreaterThan(floor);
    }
  });

  it("Projects/7 (multi-chain-evm) is ingested fully untruncated through to the tail (D-04)", () => {
    // #7 is 2,807 words < 5,000 cap → truncated:false (full sibling treatment).
    // The distinctive late-source phrase is verbatim from the tail of
    // Projects/7 - MULTI-DEX CRYPTO TRADER.md (## Summary, 2nd-to-last paragraph),
    // proving the below-fence body is ingested end-to-end, not clipped.
    // RED until 25-03 lifts the exclusion and regenerates the corpus.
    const seven = (
      portfolioContext.projects as Array<{
        page: string;
        extendedReference?: { content?: string; truncated?: boolean };
      }>
    ).find((p) => p.page === "/projects/multi-chain-evm");
    expect(seven).toBeDefined();
    expect(seven?.extendedReference?.truncated).toBe(false);
    expect(seven?.extendedReference?.content).toContain(
      "a secured local control plane with a SPA and WebSocket feed"
    );
  });

  it("corpus skills include the four additive D-08 skills (Deno, TanStack Query, Vitest, Ethers.js)", () => {
    // Machine-verifies D-08's additive refresh instead of leaving it review-only.
    // RED until 25-02 adds these to portfolio-context.static.json + 25-03 regen.
    const skills = (portfolioContext as Record<string, unknown>).skills;
    const flat: string[] = Array.isArray(skills)
      ? (skills as string[])
      : Object.values(skills as Record<string, string[]>).flat();
    for (const skill of ["Deno", "TanStack Query", "Vitest", "Ethers.js"]) {
      expect(flat).toContain(skill);
    }
  });
});

// No live project currently exceeds README_WORD_CAP (5,000 words), so the
// D-06 truncation path is exercised here with synthetic input. These cases
// call the already-exported helpers directly; they bound per-project corpus
// size, so a regression here would ship an unbounded chat context.
describe("D-06 README truncation path (synthetic fixtures)", () => {
  const CAP = 5000;
  const FENCE = "\n\n<!-- CASE-STUDY-END -->\n\n";

  /** N space-separated unique tokens for a prefix: p0 p1 ... p(N-1). */
  const words = (prefix: string, n: number): string =>
    Array.from({ length: n }, (_, i) => `${prefix}${i}`).join(" ");

  const synthMdx = (title: string): string =>
    [
      "---",
      `title: "${title}"`,
      'description: "Synthetic fixture for the D-06 truncation path"',
      'chatSummary: "Synthetic third-person summary for the truncation fixture."',
      "---",
      "Synthetic case-study body.",
    ].join("\n");

  let dir: string;
  let overPath: string;
  let underPath: string;

  beforeAll(() => {
    dir = mkdtempSync(join(tmpdir(), "chat-trunc-"));
    overPath = join(dir, "over.md");
    underPath = join(dir, "under.md");
    writeFileSync(
      overPath,
      "Case study body." +
        FENCE +
        words("a", 3000) +
        "\n\n" +
        words("b", 3000) +
        "\n\n" +
        words("c", 50),
    );
    writeFileSync(underPath, "Case study body." + FENCE + words("u", 100));
  });

  afterAll(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  it("over cap: cuts at the first paragraph break PAST the cap, not mid-paragraph", () => {
    const kept = words("a", 3000) + "\n\n" + words("b", 3000);
    const input = kept + "\n\n" + words("c", 50);
    const result = truncateReadme(input, CAP);
    expect(result).toEqual({ truncated: true, content: kept });
    expect(input.slice(result.content.length).startsWith("\n\n")).toBe(true);
    expect(wordCount(result.content)).toBeGreaterThan(CAP);
  });

  it("over cap with no paragraph break left: falls back to an exact-cap cut", () => {
    const input = words("z", 6000);
    const result = truncateReadme(input, CAP);
    expect(result).toEqual({ truncated: true, content: words("z", CAP) });
  });

  it("exactly at cap: returns the input unchanged with truncated:false", () => {
    const input = words("e", CAP);
    const result = truncateReadme(input, CAP);
    expect(result.truncated).toBe(false);
    expect(result.content).toBe(input);
  });

  it("under cap (multi-paragraph): returns the input unchanged with truncated:false", () => {
    const input = words("p", 10) + "\n\n" + words("q", 10);
    const result = truncateReadme(input, CAP);
    expect(result.truncated).toBe(false);
    expect(result.content).toBe(input);
  });

  it("buildProjectBlock attaches a truncationMarker pointing at the case study when over cap", async () => {
    const block = await buildProjectBlock({
      mdxPath: "src/content/projects/synthetic-overcap.mdx",
      mdxRaw: synthMdx("Synthetic Overcap"),
      sourceAbs: overPath,
      sourceRel: "Projects/synthetic-overcap.md",
    });
    // truncationMarker is attached conditionally, so TS's inferred JS return
    // type omits it; widen the type locally to read it.
    const ext = block.extendedReference as {
      truncated: boolean;
      truncationMarker?: string;
    };
    expect(block.page).toBe("/projects/synthetic-overcap");
    expect(ext.truncated).toBe(true);
    expect(ext.truncationMarker).toContain(
      "see /projects/synthetic-overcap",
    );
  });

  it("buildProjectBlock attaches no truncationMarker when under cap", async () => {
    const block = await buildProjectBlock({
      mdxPath: "src/content/projects/synthetic-undercap.mdx",
      mdxRaw: synthMdx("Synthetic Undercap"),
      sourceAbs: underPath,
      sourceRel: "Projects/synthetic-undercap.md",
    });
    expect(block.extendedReference.truncated).toBe(false);
    expect("truncationMarker" in block.extendedReference).toBe(false);
  });
});
